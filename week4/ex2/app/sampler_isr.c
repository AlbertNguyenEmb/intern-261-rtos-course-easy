/* Week 4 / Ex2 -- timer ISR that samples MPU6050 at SAMPLE_RATE_HZ and
 * feeds sample_queue.
 * Native FreeRTOS API only.
 */
#include "FreeRTOS.h"
#include "queue.h"
#include "task.h"

#include "main.h"
#include "params.h"
#include "datalogger_types.h"
#include "mpu6050.h"
#include "sampler_isr.h"

#define SAMPLER_TIMER_CLOCK_HZ 1000000UL
QueueHandle_t sample_queue;
static TaskHandle_t sampler_handle;
volatile uint32_t sample_errors, raw_drop_count, sample_overruns, timer_count;
volatile UBaseType_t sampler_stack_free;

void sampler_isr_init(void)
{
    /* Create the queue before enabling its producer interrupt. */
    sample_queue = xQueueCreate(32, sizeof(sensor_sample_t));
    configASSERT(sample_queue != NULL);

    /* APB1 timer clock is doubled when the APB1 prescaler is not 1.
     * With the board's 72 MHz timer clock and SAMPLE_RATE_HZ = 500:
     * PSC = 71, ARR = 1999 -> one update interrupt every 2 ms. */
    uint32_t timer_clock_hz = HAL_RCC_GetPCLK1Freq();
    if ((RCC->CFGR & RCC_CFGR_PPRE1) != 0U) {
        timer_clock_hz *= 2U;
    }
    configASSERT(timer_clock_hz >= SAMPLER_TIMER_CLOCK_HZ);
    configASSERT((timer_clock_hz % SAMPLER_TIMER_CLOCK_HZ) == 0U);
    configASSERT((SAMPLER_TIMER_CLOCK_HZ / SAMPLE_RATE_HZ) <= 65536UL);

    __HAL_RCC_TIM2_CLK_ENABLE();
    __HAL_RCC_TIM2_FORCE_RESET();
    __HAL_RCC_TIM2_RELEASE_RESET();

    TIM2->PSC = (timer_clock_hz / SAMPLER_TIMER_CLOCK_HZ) - 1U;
    TIM2->ARR = (SAMPLER_TIMER_CLOCK_HZ / SAMPLE_RATE_HZ) - 1U;
    TIM2->CNT = 0U;
    TIM2->EGR = TIM_EGR_UG;  /* Load PSC/ARR before starting the counter. */
    TIM2->SR = 0U;          /* Discard the update flag generated by UG. */

    /* Leave TIM2 disabled until the sampler task registers its handle. */
    HAL_NVIC_SetPriority(TIM2_IRQn,
                         configLIBRARY_MAX_SYSCALL_INTERRUPT_PRIORITY, 0U);
    HAL_NVIC_DisableIRQ(TIM2_IRQn);
}

void sampler_isr_start(void)
{
    sampler_handle = xTaskGetCurrentTaskHandle();
    TIM2->CNT = 0;
    TIM2->SR = 0;
    HAL_NVIC_ClearPendingIRQ(TIM2_IRQn);
    HAL_NVIC_EnableIRQ(TIM2_IRQn);
    TIM2->DIER = TIM_DIER_UIE;
    TIM2->CR1 = TIM_CR1_CEN;
}

void TIM2_IRQHandler(void)
{
    if (((TIM2->SR & TIM_SR_UIF) != 0U) &&
        ((TIM2->DIER & TIM_DIER_UIE) != 0U)) {
        TIM2->SR = ~TIM_SR_UIF;
        sampler_timer_callback();
    }
}

void sampler_timer_callback(void)
{
    BaseType_t xHigherPriorityTaskWoken = pdFALSE;
    timer_count++;
    vTaskNotifyGiveFromISR(sampler_handle, &xHigherPriorityTaskWoken);
    portYIELD_FROM_ISR(xHigherPriorityTaskWoken);
}

void sampler_task(void *arg)
{
    (void)arg;
    sampler_isr_start();
    for (;;) {
        uint32_t ticks = ulTaskNotifyTake(pdTRUE, portMAX_DELAY);
        sample_overruns += ticks - 1;
        sensor_sample_t sample = {0};
        if (!mpu6050_read_sample(&sample)) { sample_errors++; continue; }
        if (xQueueSend(sample_queue, &sample, 0) != pdPASS) raw_drop_count++;
        sampler_stack_free = uxTaskGetStackHighWaterMark(NULL);
    }
}
